/** Build the browser plugin half; React is provided by the DSH client. */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

let build
try {
  ({ build } = await import('esbuild'))
} catch {
  ({ build } = await import('../pbpkg/node_modules/esbuild/lib/main.js'))
}

const root = new URL('.', import.meta.url)
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))
const result = await build({
  absWorkingDir: import.meta.dirname,
  entryPoints: ['client-src.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  external: ['react', 'react-dom'],
  nodePaths: [join(import.meta.dirname, 'node_modules')],
  loader: { '.css': 'text' },
  legalComments: 'none',
})

await writeFile(new URL('client.js', root), `// Generated by node build-client.mjs from client-src.js.\nwindow.__ModuleLoader__.load({id:'${manifest.name}',factory(require){\nvar module={exports:{}};var exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;\n}});\n`)
console.log(`Built ${manifest.name} client (${(result.outputFiles[0].text.length / 1024).toFixed(1)} KB)`)
