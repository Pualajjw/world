import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createTerminalFixture } from './terminal-fixture.js'
const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(new URL('../../workflow-studio/package.json', import.meta.url))
const { build } = require('esbuild'), { chromium } = require('playwright-core')
const bundle = await build({ absWorkingDir: root, entryPoints: ['tests/browser-entry.js'], bundle: true, format: 'iife', platform: 'browser',
  target: 'es2022', write: false, nodePaths: [join(root, '../workflow-studio/node_modules')], loader: { '.css': 'text' } })
const terminalService = createTerminalFixture()
const browser = await chromium.launch({ executablePath: process.env.WORLD_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(8000)
const errors = []
page.on('pageerror', error => { errors.push(error.message); console.log('PAGE ERROR:', error.message) })
try {
  await mkdir(join(root, 'tmp/empty-group'), { recursive: true })
  await page.exposeBinding('__worldDesktopCall', () => ({ ok: true }))
  await page.exposeBinding('__worldBrainCall', () => ({ sessionId: 'session-1', setupRequired: false }))
  await page.exposeBinding('__worldTerminalCall', async (_source, operation, payload) => {
    try { return { ok: true, value: await terminalService.call(operation, { ...payload, cwd: root }) } }
    catch (error) { return { ok: false, error: { message: error.message, code: error.code } } }
  })
  await page.route('http://127.0.0.1/empty-group', route => route.fulfill({ contentType: 'text/html', body:
    '<!doctype html><html style="--dsh-windows-titlebar-height:40px"><head><style>body{margin:0}#root{height:100vh;width:100vw}.app-frame{position:relative;height:100%}#host-ui{position:absolute;inset:40px 0 0}</style></head><body><div id="root"><div class="app-frame"><main id="host-ui"></main><div id="overlay-root" data-shell-overlay></div></div></div></body></html>' }))
  await page.goto('http://127.0.0.1/empty-group')
  await page.evaluate(() => localStorage.setItem('dsh.world.apps', JSON.stringify(['vscode', 'terminal'])))
  await page.addScriptTag({ content: bundle.outputFiles[0].text })
  await page.locator('[data-world-icon-id="vscode"]').dblclick()
  const editor = page.locator('.world-vscode-window[data-world-vscode-key]')
  await editor.locator('.world-vscode-welcome').waitFor()
  await page.locator('[data-world-icon-id="terminal"]').dblclick()
  const terminal = page.locator('.world-terminal-window'), input = terminal.getByRole('textbox').first()
  await input.fill('echo keep-terminal-draft')
  const title = terminal.locator('.world-vscode-titlebar')
  await title.evaluate(node => node.closest('section').getAnimations().forEach(animation => animation.finish()))
  const from = await title.boundingBox(), to = await editor.locator('.world-vscode-pane').boundingBox()
  await page.mouse.move(from.x + 100, from.y + 20); await page.mouse.down()
  await page.mouse.move(to.x + to.width / 2, to.y + to.height * .1, { steps: 15 }); await page.mouse.up()
  const panes = editor.locator('.world-vscode-pane:not(.is-hidden)')
  await page.waitForFunction(() => document.querySelectorAll('.world-vscode-pane:not(.is-hidden)').length === 2)
  console.log('docked terminal above empty group')
  assert.equal(await panes.nth(1).locator('.world-vscode-welcome').isVisible(), true)
  await page.screenshot({ path: join(root, 'tmp/empty-group/docked.png') })
  await editor.getByRole('button', { name: 'src', exact: true }).click()
  await editor.getByRole('button', { name: 'main.js', exact: true }).click()
  await editor.getByRole('tab', { name: /main.js/u }).waitFor()
  assert.equal(await panes.nth(1).locator('.world-vscode-welcome').isVisible(), true, 'opening a file in the other group must keep the empty group welcome')
  console.log('opened file', await panes.evaluateAll(nodes => nodes.map(n => ({ group: n.dataset.worldPane, tabs: n.querySelectorAll('[role=tab]').length, text: n.innerText.slice(0,70) }))))
  await page.screenshot({ path: join(root, 'tmp/empty-group/opened.png') })
  const bottom = await panes.nth(1).boundingBox()
  await editor.getByRole('tab', { name: /main.js/u }).dragTo(panes.nth(1), { targetPosition: { x: bottom.width / 2, y: bottom.height * .7 } })
  console.log('tab drop returned')
  await page.waitForTimeout(200)
  console.log('after drop', await panes.evaluateAll(nodes => nodes.map(n => ({ group: n.dataset.worldPane, tabs: n.querySelectorAll('[role=tab]').length, text: n.innerText.slice(0,70) }))))
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.locator('.world-start.open').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await panes.count(), 2, 'drop into an empty group fills that group without another empty pane')
  assert.equal(await panes.nth(0).locator('.world-terminal-window').count(), 1)
  assert.equal(await panes.nth(1).locator('.world-vscode-textarea').count(), 1)
  const geometry = await panes.evaluateAll(nodes => nodes.map(node => {
    const box = node.getBoundingClientRect(); return { x: box.x, y: box.y, width: box.width, height: box.height }
  }))
  assert.equal(geometry[0].x, geometry[1].x)
  assert.equal(geometry[0].width, geometry[1].width)
  assert.ok(Math.abs(geometry[0].y + geometry[0].height - geometry[1].y) < 1)
  assert.ok(Math.abs(geometry[0].height - geometry[1].height) < 1)
  assert.equal(await page.locator('.world-dock-drag-shield').count(), 0)
  assert.equal(await input.inputValue(), 'echo keep-terminal-draft')
  assert.deepEqual(errors, [])
  await page.screenshot({ path: join(root, 'tmp/empty-group/fixed.png') })
  const sash = editor.getByRole('separator', { name: '调整分屏比例' })
  await sash.evaluate(node => node.addEventListener('pointerdown', event => { node.dataset.testPointer = event.pointerId }, { once: true }))
  const separator = await sash.boundingBox()
  await page.mouse.move(separator.x + separator.width / 2, separator.y + separator.height / 2); await page.mouse.down()
  await page.mouse.move(separator.x + separator.width / 2 + 1, separator.y + separator.height / 2)
  await sash.evaluate(node => node.releasePointerCapture(Number(node.dataset.testPointer)))
  await page.mouse.move(separator.x + separator.width / 2, separator.y + separator.height + 30)
  assert.equal(await sash.evaluate(node => node.classList.contains('is-dragging')), false, 'lost pointer capture ends divider drag')
  await page.mouse.up()
  await editor.locator('[data-tab-id="app:terminal"] .world-vscode-tab-close').click()
  await page.locator('[data-world-taskbar="terminal"]').click()
  await title.waitFor()
  await title.evaluate(node => node.closest('section').getAnimations().forEach(animation => animation.finish()))
  const floating = await title.boundingBox()
  await page.mouse.move(floating.x + 100, floating.y + 20); await page.mouse.down()
  await page.mouse.move(floating.x + 140, floating.y + 70, { steps: 4 })
  assert.equal(await page.locator('.world-dock-drag-shield').count(), 1)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  assert.equal(await page.locator('.world-dock-drag-shield').count(), 0, 'lost window focus removes the desktop-wide mouse shield')
  await page.mouse.up()
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.locator('.world-start.open').waitFor(); await page.keyboard.press('Escape')
  assert.equal(await input.inputValue(), 'echo keep-terminal-draft')
  console.log(`Empty group drag passed: ${JSON.stringify(geometry)}; terminal above, file below, taskbar clickable, draft preserved, lost capture and blur cleanup.`)
} finally { await browser.close(); await terminalService.dispose() }
