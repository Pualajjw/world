import assert from 'node:assert/strict'
import { createDesktopBridge } from '../desktop-bridge.js'
import { createHerMessage } from '../her-message.js'
import { existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
let build
try { ({ build } = await import('esbuild')) } catch {
  ({ build } = await import(pathToFileURL(join(root, '../pbpkg/node_modules/esbuild/lib/main.js'))))
}
const require = (await import('node:module')).createRequire(join(root, '../workflow-studio/package.json'))
const { chromium } = require('playwright-core')
const browserPath = process.env.WORLD_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'
if (!existsSync(browserPath)) { console.log('no browser'); process.exit(0) }

const bundle = await build({
  absWorkingDir: root, entryPoints: ['tests/browser-entry.js'], bundle: true, format: 'iife', platform: 'browser',
  target: 'es2022', write: false, nodePaths: [join(root, '../workflow-studio/node_modules')],
  loader: { '.css': 'text' }, legalComments: 'none',
})
const html = '<!doctype html><html data-windows-titlebar style="--dsh-windows-titlebar-height:40px"><head><style>#root{position:relative;width:100vw;height:100vh}.app-frame{position:relative;width:100%;height:100%;padding-top:var(--dsh-windows-titlebar-height);box-sizing:border-box}#host-ui{position:absolute;inset:var(--dsh-windows-titlebar-height) 0 0;background:#262626}[data-shell-overlay]{position:absolute;inset:0;z-index:20;pointer-events:none}[data-shell-overlay]>*{pointer-events:auto}</style></head><body><div id="root"><div class="app-frame"><main id="host-ui"></main><div id="overlay-root" data-shell-overlay></div></div></div></body></html>'
const shots = join(root, 'tmp/vscode-chat-context')
mkdirSync(shots, { recursive: true })

const browser = await chromium.launch({ executablePath: browserPath, headless: true })
const bridge = createDesktopBridge()
const prompts = []
const service = createHerMessage({ bridge, brain: { get: async () => ({ sessionId: 'fixed', profile: {} }) }, controller: { prompt: async request => { prompts.push(request) } } })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setContent(html)
  await page.exposeBinding('__worldDesktopCall', (_page, operation, payload) => bridge.call(operation, payload))
  await page.exposeBinding('__worldHerMessage', (_page, operation, payload) => service.call(operation, payload))
  await page.addScriptTag({ content: bundle.outputFiles[0].text })
  await page.waitForFunction(() => document.body.dataset.worldWindow === 'closed')
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.locator('.world-app-card[data-world-app-card="vscode"] .world-app-install').click()
  await page.locator('.world-app-card[data-world-app-card="vscode"] .world-app-open').click()
  const editor = page.locator('.world-vscode-window[data-world-vscode-key]')
  await editor.waitFor()
  await page.waitForTimeout(300)
  await editor.getByRole('button', { name: 'src', exact: true }).click()
  await editor.getByRole('button', { name: 'main.js', exact: true }).dblclick()
  const input = editor.getByRole('textbox', { name: '编辑 main.js', exact: true })
  await input.waitFor()
  await input.focus()
  await input.evaluate(node => node.setSelectionRange(6, 11))
  const taskbar = page.locator('[data-world-her-message] input').first()
  const replyButton = page.locator('.world-her-reply'), card = page.getByRole('complementary', { name: '她的答复' })
  const buttonRect = await replyButton.boundingBox(), formRect = await page.locator('.world-her-compose').boundingBox()
  const gap = formRect.x - buttonRect.x - buttonRect.width
  assert.deepEqual([buttonRect.width, buttonRect.height, gap], [26, 26, 6])
  assert.equal(await replyButton.isDisabled(), true)
  await taskbar.click()
  await taskbar.fill('这段代码什么意思？')
  await taskbar.dispatchEvent('keydown', { key: 'Enter', keyCode: 229, isComposing: true })
  assert.equal(prompts.length, 0)
  assert.equal(await input.inputValue(), 'const value = 1\n')
  assert.deepEqual(await input.evaluate(node => [node.selectionStart, node.selectionEnd]), [6, 11])
  const caret = editor.locator('.world-taskbar-source-caret')
  assert.equal(await caret.count(), 1)
  assert.ok((await caret.boundingBox()).height > 0)
  await taskbar.press('Enter')
  await page.locator('.world-her-reply:enabled').waitFor()
  assert.equal(await card.count(), 0)
  const snapshot = JSON.parse(prompts[0].content[1].text.split('\n').slice(1).join('\n'))
  assert.equal(snapshot.view.text, 'value'); assert.equal(snapshot.view.from, 1)
  assert.equal(snapshot.view.path, '/workspace/src/main.js')
  assert.equal((await service.read({ reference: snapshot.reference, windowId: snapshot.active }, 'fixed')).text, 'value')
  const activity = messages => bridge.setActivity({ sessionId: 'fixed', messages, phase: 'responding' })
  activity([{ role: 'assistant', text: '不相关的回复', requestId: 'different' }])
  assert.equal(await replyButton.getAttribute('data-unread'), 'false')
  activity([{ role: 'assistant', text: '这是一个变量名。', requestId: prompts[0].requestId }])
  await page.getByRole('button', { name: '查看她的新回复' }).waitFor()
  assert.equal(await card.count(), 0)
  assert.equal(await taskbar.evaluate(node => document.activeElement === node), true)
  await page.screenshot({ path: join(shots, 'taskbar-two-carets.png') })
  await replyButton.click()
  await card.getByText('这是一个变量名。').waitFor()
  assert.equal(await taskbar.evaluate(node => document.activeElement === node), true)
  // 桌面卡片：520 宽、贴在任务栏上方、不出屏（手机见下面的整屏断言）。
  const cardBox = await card.boundingBox(), viewBox = page.viewportSize()
  const barBox = await page.locator('.world-taskbar').boundingBox()
  assert.ok(Math.abs(cardBox.width - 520) <= 1, `桌面答复卡片宽度 ${cardBox.width}`)
  assert.ok(cardBox.y + cardBox.height <= barBox.y + 1, '卡片在任务栏上方')
  assert.ok(cardBox.x >= 0 && cardBox.x + cardBox.width <= viewBox.width, '卡片不出屏')
  await page.screenshot({ path: join(shots, 'taskbar-summary.png') })
  // 长答复：卡片高度封在 64vh，正文自己滚，别把任务栏顶出屏。
  activity([{ role: 'assistant', text: '她写了一段很长的答复。'.repeat(120), requestId: prompts[0].requestId }])
  await card.getByText(/她写了一段很长的答复。她写了一段/).first().waitFor()
  const tall = await card.boundingBox(), para = card.locator('p')
  assert.ok(tall.height <= viewBox.height * .64 + 1, `长答复卡在 64vh 以内（${Math.round(tall.height)}）`)
  assert.ok(await para.evaluate(node => node.scrollHeight > node.clientHeight), '长答复在卡片里滚动')
  assert.ok(tall.y + tall.height <= barBox.y + 1, '长答复也不压任务栏')
  await page.screenshot({ path: join(shots, 'taskbar-answer-long.png') })
  activity([{ role: 'assistant', text: '这是一个变量名。', requestId: prompts[0].requestId }])
  await card.getByText('这是一个变量名。').waitFor()
  await card.getByRole('button', { name: '关闭答复' }).click()
  assert.equal(await card.count(), 0)
  assert.equal(await replyButton.evaluate(node => document.activeElement === node), true, '关闭后焦点回到答复按钮')
  await replyButton.click()
  await card.getByText('这是一个变量名。').waitFor()
  await card.getByRole('button', { name: '回到代码' }).click()
  assert.equal(await input.evaluate(node => document.activeElement === node), true)
  assert.equal(await caret.count(), 0)
  assert.equal(await replyButton.getAttribute('data-unread'), 'false')
  const expand = async () => {
    await replyButton.click()
    await card.getByRole('button', { name: '展开对话' }).click()
  }
  await page.evaluate(() => window.__worldTesting.conversation.setMessages('fixed', [{ id: 'old', role: 'assistant', text: '之前的答复' }]))
  await expand()
  const conversation = page.getByRole('region', { name: '和她的对话 窗口' })
  const followup = conversation.locator('[data-fixture-composer="fixed"] textarea')
  await conversation.getByText('assistant: 之前的答复').waitFor()
  assert.equal(await card.count(), 0)
  assert.equal(await conversation.evaluate(node => Boolean(node.closest('.world-taskbar'))), false)
  await followup.fill('那它在哪里赋值？'); await followup.press('Enter')
  assert.deepEqual(await page.evaluate(() => window.__worldTesting.conversation.sent.at(-1)), { sessionId: 'fixed', text: '那它在哪里赋值？' })
  await page.screenshot({ path: join(shots, 'taskbar-conversation.png') })
  await followup.fill('留在原会话的草稿')
  await conversation.getByRole('button', { name: '最小化' }).click()
  await followup.waitFor({ state: 'detached' })
  await expand()
  assert.equal(await followup.inputValue(), '留在原会话的草稿')
  await expand()
  assert.equal(await page.locator('[data-world-plugin="world-conversation:fixed"]').count(), 1)
  await conversation.getByRole('button', { name: '关闭' }).click()
  await page.waitForFunction(() => window.__worldTesting.conversation.retainCount('fixed') === 0)
  assert.deepEqual(await page.evaluate(() => window.__worldTesting.conversation.conflicts), [])
  await input.focus()
  await input.evaluate(node => node.setSelectionRange(3, 3))
  await taskbar.click(); await taskbar.fill('没选中时呢'); await taskbar.press('Enter')
  await page.waitForFunction(() => window.__worldTesting.calls.filter(call => call.method === 'world-her-message/insert').length === 2)
  const second = await page.evaluate(() => window.__worldTesting.calls.filter(call => call.method === 'world-her-message/insert').at(-1).payload.context)
  assert.equal(second.view.kind, '可见代码'); assert.equal(second.view.column, 4); assert.match(second.view.text, /const value/)
  await input.focus()
  await input.selectText()
  await input.evaluate(() => document.dispatchEvent(new Event('selectionchange')))

  await editor.getByRole('button', { name: '打开对话' }).click()
  const chat = page.locator('.world-vscode-chat')
  await chat.locator('[data-fixture-composer]').waitFor()
  const bar = chat.locator('.world-vscode-chat-context')
  await bar.waitFor()
  assert.match(await bar.innerText(), /main\.js/, '上下文条显示最近编辑的文件')
  assert.match(await bar.innerText(), /第 1 行 · 选中 1 行/, '光标行与选区行数')
  const draft = chat.locator('[data-fixture-composer] textarea')
  assert.equal(await draft.inputValue(), '', '初始输入框为空')

  await bar.getByRole('button', { name: '+ 选区' }).click()
  const quoted = await draft.inputValue()
  assert.match(quoted, /【编辑器上下文】\/workspace\/src\/main\.js 第 1 行/)
  assert.match(quoted, /```javascript\nconst value = 1\n```/)

  await bar.getByRole('button', { name: '+ 文件' }).click()
  const withFile = await draft.inputValue()
  assert.ok(withFile.startsWith(quoted), '第二次引用追加在已有内容后面')
  assert.match(withFile, /【编辑器上下文】\/workspace\/src\/main\.js\n光标：第 1 行，第 1 列/)
  assert.match(await bar.locator('.world-vscode-chat-context-meta').innerText(), /已加入输入框/)

  // 真发送一次：上下文确实进入会话消息
  await chat.getByRole('button', { name: '发送', exact: true }).click()
  const sent = await page.evaluate(() => window.__worldTesting.conversation.sent.at(-1))
  assert.equal(sent.sessionId, 'session-1')
  assert.match(sent.text, /const value = 1/)
  await page.screenshot({ path: join(shots, 'context.png') })

  // 关掉对话再打开：快照还在，不用重新选一遍
  await page.locator('.world-vscode-tab.active .world-vscode-tab-close').click()
  await page.waitForFunction(() => document.querySelector('.world-vscode-chat') === null)
  await editor.getByRole('button', { name: '打开对话' }).click()
  await chat.locator('[data-fixture-composer]').waitFor()
  await chat.locator('.world-vscode-chat-context').waitFor()
  assert.match(await chat.locator('.world-vscode-chat-context').innerText(), /main\.js/)
  activity([{ role: 'assistant', text: '这次看的是可见代码。', requestId: prompts[1].requestId }])
  await page.getByRole('button', { name: '查看她的新回复' }).waitFor()
  await page.setViewportSize({ width: 390, height: 640 })
  await page.locator('.world-her-message.is-phone').waitFor()
  assert.equal(await replyButton.getAttribute('data-unread'), 'true')
  assert.equal(await card.count(), 0)
  await page.screenshot({ path: join(shots, 'taskbar-phone-unread.png') })
  // 手机：答复铺满一屏，让开标题栏 + 状态栏，并把任务栏盖住。
  await replyButton.click()
  await card.waitFor()
  const phoneCard = await card.boundingBox(), phoneView = page.viewportSize()
  const phoneTop = await page.locator('.world-phone-status').evaluate(node => Math.round(node.getBoundingClientRect().bottom))
  assert.deepEqual({ x: Math.round(phoneCard.x), y: Math.round(phoneCard.y), w: Math.round(phoneCard.width), h: Math.round(phoneCard.height) },
    { x: 0, y: phoneTop, w: phoneView.width, h: phoneView.height - phoneTop }, '手机答复整屏')
  await page.screenshot({ path: join(shots, 'taskbar-phone-answer.png') })
  await card.getByRole('button', { name: '关闭答复' }).click()
  assert.equal(await card.count(), 0)
  await expand()
  assert.equal(await followup.inputValue(), '留在原会话的草稿')
  assert.equal(await page.locator('[data-fixture-composer]').count(), 1)
  await conversation.getByRole('button', { name: '关闭' }).click()
  assert.deepEqual(await page.evaluate(() => window.__worldTesting.conversation.conflicts), [])
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ result: 'passed', replyButton: [buttonRect.width, buttonRect.height], gap, quoted: quoted.length, shots }))
} finally {
  bridge.dispose()
  await browser.close()
}
